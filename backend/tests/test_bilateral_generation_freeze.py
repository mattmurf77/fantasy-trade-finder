def arguments(case):
    args=companion_world()
    if case=='neutral':args=world()
    elif case=='unknown':args['opponent_sources']={'partner':{}}
    elif case=='partial':args['pinned_give_players']=['give','missing']
    elif case=='invalid_floor':args['fairness_threshold']=float('nan')
    elif case=='exact':args.update(pinned_give_players=['give'],exact_give=True)
    elif case=='pair_budget':args['config']={'owner_pair_budget':1}
    elif case=='total_budget':args['config']={'owner_total_budget':1}
    elif case=='expired':args['manager_preferences']={'viewer':{'expired_pick_ids':['give']}}
    elif case=='untouchable':args['manager_preferences']={'partner':{'untouchables':['target']}}
    elif case=='last_wins':
        args=favorable(outlook='jets',opponent_outlooks={'partner':'jets'},
            manager_preferences={'viewer':{'expired_pick_ids':['give'],'own_next_draft_pick_ids':['give']},
                                 'partner':{'expired_pick_ids':['target'],'own_next_draft_pick_ids':['target']}})
    elif case=='previous_disposition':args['exclusion_keys']={(frozenset(['give']),frozenset(['target']))}
    return args


def digest(value):
    return hashlib.sha256(json.dumps(value,sort_keys=True,separators=(',',':'),allow_nan=False).encode()).hexdigest()


def generated_value(module,args,*,dynamic=False):
    cards,report=module.generate_bilateral_trades(**deepcopy(args))
    values=[dict(vars(c)) if dynamic else asdict(c) for c in cards]
    for card in values:
        for key in ('trade_id','created_at','expires_at'):card.pop(key,None)
    data=report.as_dict();data.pop('elapsed_seconds',None)
    def frozen(value):
        if is_dataclass(value):return asdict(value)
        raise TypeError(type(value).__name__)
    return json.loads(json.dumps([values,data],default=frozen,allow_nan=False))


def external_cards(args):
    return [terms(args,['give'],['target']),terms(args,['missing'],['target']),
            terms(args,['give','give'],['target']),terms(args,['extra'],['target'])]


@pytest.mark.parametrize('give,eligible',[('give',True),('extra',False)])
def test_named_red_core_freezes_only_once(monkeypatch,give,eligible):
    args=companion_world();search=candidate._Search(**args);calls=[];dump=owner._dump
    def observe(data):
        if 'eligible' in data and 'selection' in data:calls.append(data)
        return dump(data)
    monkeypatch.setattr(owner,'_dump',observe)
    with ts._cfg_override(search.config),ts.stud_tax_override('market'):
        proof=search._core(terms(args,[give],['target']))
    assert proof.eligible is eligible and len(calls)==1
    assert isinstance(proof,owner.OwnerDecisionContext)
    assert proof.as_dict()['generator_version']==candidate.VERSION


