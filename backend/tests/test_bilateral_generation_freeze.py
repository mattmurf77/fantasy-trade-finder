def test_new_snapshot_consumer_aborts_real_generation(monkeypatch):
    evaluate=candidate._Search.evaluate
    def consumer(self,card,**kwargs):
        proof=evaluate(self,card,**kwargs)
        if not proof.eligible:proof.as_dict()
        return proof
    monkeypatch.setattr(candidate._Search,'evaluate',consumer)
    with pytest.raises(RuntimeError,match='Internal generation rejection'):
        candidate.generate_bilateral_trades(**companion_world())


